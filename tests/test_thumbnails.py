def png(width: int, height: int, pixel, colour: int = 6, filt: int = 0) -> bytes:
    """a png filled by pixel(x, y) -> bytes, every row with the given filter type
    (only 0 and 2 are written properly; enough to exercise the decoder)"""
    rows, prev = [], None
    for y in range(height):
        line = b"".join(pixel(x, y) for x in range(width))
        if filt == 2 and prev is not None:
            rows.append(b"\2" + bytes((a - b) & 255 for a, b in zip(line, prev)))
        else:
            rows.append(b"\0" + line)
        prev = line

    def chunk(kind, body):
        return struct.pack(">I", len(body)) + kind + body + struct.pack(">I", zlib.crc32(kind + body))

    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, colour, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(b"".join(rows))) + chunk(b"IEND", b""))


# a red square in the middle of a clear 40 x 40 picture
def square(x, y):
    return b"\xff\0\0\xff" if 10 <= x < 30 and 10 <= y < 30 else b"\0\0\0\0"


GCODE = ("; HEADER_BLOCK_START\n; generated by OrcaSlicer 2.5.2\n; HEADER_BLOCK_END\n\n"
         "; EXECUTABLE_BLOCK_START\nG28\n; EXECUTABLE_BLOCK_END\n\n"
         "; CONFIG_BLOCK_START\n; thumbnails = 96x96/PNG, 300x300/PNG, 50x50/JPG\n"
         "; thumbnails_format = PNG\n; CONFIG_BLOCK_END\n")


class PngTests(unittest.TestCase):
    def test_round_trip(self):
        data = png(5, 3, lambda x, y: bytes((x * 40, y * 80, 7, 255)), filt=2)
        w, h, rgba = thumbnails.decode(data)
        self.assertEqual((w, h), (5, 3))
        self.assertEqual(rgba[(2 * 5 + 4) * 4:(2 * 5 + 4) * 4 + 4], bytes((160, 160, 7, 255)))
        self.assertEqual(thumbnails.decode(thumbnails.encode(w, h, rgba))[2], rgba)

    def test_rgb_and_grey(self):
        self.assertEqual(thumbnails.decode(png(1, 1, lambda x, y: b"\1\2\3", colour=2))[2], b"\1\2\3\xff")
        self.assertEqual(thumbnails.decode(png(1, 1, lambda x, y: b"\x80", colour=0))[2], b"\x80\x80\x80\xff")

    def test_refuses_what_it_cant_read(self):
        with self.assertRaises(ValueError):
            thumbnails.decode(b"GIF89a")

    def test_fit_crops_to_the_subject_and_centres_it(self):
        w, h, rgba = thumbnails.decode(png(40, 40, square))
        out = thumbnails.fit(w, h, rgba, 30, 20)
        pixel = lambda x, y: bytes(out[(y * 30 + x) * 4:(y * 30 + x) * 4 + 4])
        self.assertEqual(pixel(15, 10), b"\xff\0\0\xff")   # middle: the square
        self.assertEqual(pixel(0, 10), b"\0\0\0\0")        # wide box: clear at the sides
        self.assertEqual(pixel(15, 0)[3], 0)                # a small margin is kept


class GcodeTests(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.tmp, ignore_errors=True)
        self.project = self.tmp / "p.3mf"
        with zipfile.ZipFile(self.project, "w") as z:
            z.writestr("Metadata/plate_1.png", png(40, 40, square))
            z.writestr("Metadata/plate_2.png", png(40, 40, lambda x, y: b"\0\0\xff\xff"))

    def gcode(self, text=GCODE, name="plate_1.gcode") -> Path:
        path = self.tmp / name
        path.write_bytes(text.encode())
        return path

    def blocks(self, path: Path) -> dict:
        text = path.read_text()
        found = {}
        for m in re.finditer(r"; thumbnail begin (\d+)x(\d+) (\d+)\r?\n((?:; .*\r?\n)+?); thumbnail end", text):
            data = "".join(line[2:].strip() for line in m.group(4).splitlines())
            self.assertEqual(len(data), int(m.group(3)))
            self.assertTrue(all(len(line) <= 80 for line in m.group(4).splitlines()))
            found[(int(m.group(1)), int(m.group(2)))] = thumbnails.decode(base64.b64decode(data))
        return found

    def test_sizes_come_from_the_gcode_settings(self):
        self.assertEqual(thumbnails.wanted_sizes(self.gcode()), [(96, 96), (300, 300)])
        old = self.gcode("; thumbnails = 140x110\n; thumbnails_format = PNG\n", "old.gcode")
        self.assertEqual(thumbnails.wanted_sizes(old), [(140, 110)])
        self.assertEqual(thumbnails.wanted_sizes(self.gcode("G28\n", "none.gcode")), [])

    def test_adds_them_after_the_header(self):
        path = self.gcode()
        self.assertTrue(thumbnails.add(path, self.project))
        text = path.read_text()
        self.assertTrue(text.startswith("; HEADER_BLOCK_START\n; generated by OrcaSlicer 2.5.2\n"
                                        "; HEADER_BLOCK_END\n\n; THUMBNAIL_BLOCK_START\n"))
        self.assertIn("; THUMBNAIL_BLOCK_END\n\n; EXECUTABLE_BLOCK_START\nG28\n", text)
        found = self.blocks(path)
        self.assertEqual(sorted(found), [(96, 96), (300, 300)])
        self.assertEqual(found[(96, 96)][:2], (96, 96))
        self.assertFalse(thumbnails.add(path, self.project), "only once")

    def test_picks_the_plate_from_the_file_name(self):
        path = self.gcode(name="plate_2.gcode")
        self.assertTrue(thumbnails.add(path, self.project))
        rgba = self.blocks(path)[(96, 96)][2]
        self.assertEqual(bytes(rgba[:4]), b"\0\0\xff\xff")   # plate 2 is all blue

    def test_keeps_windows_line_ends(self):
        path = self.gcode(GCODE.replace("\n", "\r\n"))
        self.assertTrue(thumbnails.add(path, self.project))
        data = path.read_bytes()
        self.assertNotIn(b"\n", data.replace(b"\r\n", b""))
        self.assertEqual(len(self.blocks(path)), 2)

    def test_nothing_to_add(self):
        self.assertFalse(thumbnails.add(self.gcode("G28\n"), self.project))
        bare = self.tmp / "bare.3mf"
        with zipfile.ZipFile(bare, "w") as z:
            z.writestr("3D/3dmodel.model", "")
        path = self.gcode()
        self.assertFalse(thumbnails.add(path, bare))
        self.assertEqual(path.read_text(), GCODE)
        self.assertFalse(thumbnails.add(self.tmp / "missing.gcode", self.project))


if __name__ == "__main__":
    unittest.main()
